ETL_BEGIN = "<!-- etl:begin (generated by `factorysim report --section etl`; do not edit) -->"
ETL_END = "<!-- etl:end -->"
SAMPLES = {
    "mes_production_v1.csv": ("mes_production", "20250308"),
    "mes_production_v2.csv": ("mes_production", "20250701"),
    "erp_invoices.csv": ("erp_invoices", "20250102"),
    "erp_goods_receipts.csv": ("erp_goods_receipts", "20250109"),
    "cmms_work_orders.jsonl": ("cmms_work_orders", "20250130"),
    "bank_statement.csv": ("bank_statements", "20250101"),
}
SAMPLE_LINES = 8


SWEEP_DEFECT_SEEDS = range(1, 9)
WEEKLY = 7


def build_etl_results(build: Path, defect_seed: int = 7, batch_days: int | None = None) -> dict:
    """Export, run the pipeline (once, or every ``batch_days`` days of arrivals) and score it."""
    from .etl.pipeline import run_pipeline
    from .evaluation import evaluate
    from .sources.export import export_sources

    conn = create_database(build / "truth" / "factory.db", overwrite=True)
    try:
        run_simulation(conn, SimConfig())
        exported = export_sources(
            conn, build / "landing", build / "truth" / "defects.jsonl", seed=defect_seed
        )
    finally:
        conn.close()
    # In batched mode, remember when each exception was first raised, to measure alarms
    # that later cleared and how long business errors took to surface.
    first_raised: dict[tuple, date] = {}
    if batch_days:
        through = date(2025, 1, 1)
        while through < date(2026, 1, 15):
            run_pipeline(build / "landing", build / "lake", through)
            for check, day, key in (
                duckdb.connect()
                .execute(
                    "SELECT check_name, business_date, key FROM read_parquet("
                    f"'{build / 'lake' / 'gold' / 'recon_results' / '*.parquet'}') "
                    "WHERE status = 'exception'"
                )
                .fetchall()
            ):
                first_raised.setdefault((check, str(day), key), through)
            through += timedelta(days=batch_days)
    run = run_pipeline(build / "landing", build / "lake")
    evaluation = evaluate(
        build / "truth" / "factory.db", build / "truth" / "defects.jsonl", build / "lake"
    )
    if batch_days:
        final = {
            tuple(map(str, r))
            for r in duckdb.connect()
            .execute(
                "SELECT check_name, business_date, key FROM read_parquet("
                f"'{build / 'lake' / 'gold' / 'recon_results' / '*.parquet'}') "
                "WHERE status = 'exception'"
            )
            .fetchall()
        }
        delays = [
            (first_raised[tuple(k)] - date.fromisoformat(k[1])).days
            for k in evaluation["business_error_rows"]
            if tuple(k) in first_raised
        ]
        evaluation["batched"] = {
            "transient_exceptions": len(set(first_raised) - final),
            "business_error_rows_raised": len(delays),
            "max_days_to_raise": max(delays, default=None),
            "median_days_to_raise": sorted(delays)[len(delays) // 2] if delays else None,
        }
    return json.loads(
        json.dumps(
            {
                "defect_seed": defect_seed,
                "batch_days": batch_days,
                "export": asdict(exported),
                "pipeline": {
                    "files_loaded": run.files_loaded,
                    "duplicate_files": run.duplicate_files,
                    "entities": [asdict(e) for e in run.entities],
                    "recon": run.recon,
                },
                "evaluation": evaluation,
            },
            default=str,
        )
    )


def sweep_summary(results: dict) -> dict:
    """The handful of numbers that must hold for every defect seed."""
    ev = results["evaluation"]
    r, q = ev["reconciliation"], ev["quarantine"]
    data = [d for d in ev["defects"] if d["kind"] != "normalization"]
    batched = ev.get("batched") or {}
    return {
        "defect_seed": results["defect_seed"],
        "batches": ev["batches"],
        "late_files_in_later_batch": ev["late_files_in_later_batch"],
        "transient_exceptions": batched.get("transient_exceptions"),
        "max_days_to_raise": batched.get("max_days_to_raise"),
        "defects_injected": sum(d["injected"] for d in data),
        "defects_handled": sum(d["handled"] for d in data),
        "quarantine_precision": q["precision"],
        "quarantine_recall": q["recall"],
        "business_errors": r["expected_business_errors"],
        "business_errors_caught": r["business_errors_caught"],
        "business_errors_open": r["business_errors_open"],
        "data_loss_rows": r["expected_data_loss_rows"],
        "data_loss_rows_flagged_with_evidence": r["data_loss_rows_with_evidence"],
        "unexpected_exceptions": len(r["unexpected_exceptions"]),
        "unexplained_cells": sum(c["unexplained"] for c in ev["gold_vs_truth"].values()),
    }


def write_samples(build: Path, out_dir: Path) -> None:
    """Copy the first lines of a few landed files, re-encoded as UTF-8 for display."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, (source, day) in SAMPLES.items():
        path = next(iter(sorted((build / "landing" / source).rglob(f"*_{day}.*"))))
        payload = path.read_bytes()
        try:
            text = payload.decode("utf-8-sig")
        except UnicodeDecodeError:
            text = payload.decode("cp1252")
        lines = text.splitlines(keepends=True)[:SAMPLE_LINES]
        (out_dir / name).write_text("".join(lines), encoding="utf-8", newline="")


def render_etl_block(results: dict, sweep: list[dict]) -> str:
    ev, pipe, exp = results["evaluation"], results["pipeline"], results["export"]
    q, r = ev["quarantine"], ev["reconciliation"]
    records = sum(e["records"] for e in pipe["entities"])

    def defect_table(kind: str) -> list[str]:
        rows = ["| Defect | Injected | Handled | What was checked |", "|---|---:|---:|---|"]
        for d in ev["defects"]:
            if d["kind"] == kind:
                rows.append(
                    f"| `{d['defect']}` | {d['injected']:,} | {d['handled']:,} | {d['how']} |"
                )
        return rows

    lines = [
        ETL_BEGIN,
        "",
        f"One year of exports: {exp['files_written']:,} files and {records:,} records. "
        f"The pipeline loaded {pipe['files_loaded']:,} files and skipped "
        f"{pipe['duplicate_files']} re-delivered duplicates.",
        "",
        "**Data defects** (each check compares the outcome with the truth):",
        "",
        *defect_table("data"),
        "",
        "**Business errors** (correct-looking records that only reconciliation can catch):",
        "",
        *defect_table("business_error"),
        "",
        "**Normalization** (reported separately: the alias tables are maintained reference "
        "data written to match the exporter's legacy codes, so this mostly shows the mapping "
        "is applied):",
        "",
        *defect_table("normalization"),
        "",
        f"**Quarantine:** {q['quarantined']} records quarantined; precision "
        f"{q['precision']:.0%} and recall {q['recall']:.0%} against the injected "
        f"unrecoverable records, {q['correct_reason']} of {q['true_positives']} with the "
        "expected reason code.",
        "",
        "| Reconciliation check | Rows | Matched | Open (late window) | Exceptions "
        "| ...with quarantine evidence |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, c in pipe["recon"].items():
        lines.append(
            f"| `{name}` | {c['rows']:,} | {c['matched']:,} | {c['open']} | "
            f"{c['exceptions']} | {c['with_evidence']} |"
        )
    lines += [
        "",
        f"All {r['exceptions']} exceptions trace back to an injected defect; "
        f"{len(r['unexpected_exceptions'])} have no injected cause. Injected business errors: "
        f"{r['business_errors_caught']} rows are exceptions and {r['business_errors_open']} "
        "more were still inside the late-arrival window at the end of the year. Injected lost "
        f"records: {r['data_loss_rows_with_evidence']} of the {r['expected_data_loss_rows']} "
        "rows they touch are raised (as exceptions, or as open if recent) with the lost "
        "record attached as evidence. "
        f"Business-error rows that also carry quarantine evidence from the same day, where an "
        f"analyst has to look past it: {r['business_errors_with_evidence']}.",
        "",
        "**Gold vs. ground truth** (cells compared against the simulator's database):",
        "",
        "| Dataset | Cells | Exact | Differs only by injected losses or errors | Unexplained |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, c in ev["gold_vs_truth"].items():
        lines.append(
            f"| {name.replace('_', ' ')} | {c['cells']:,} | {c['exact']:,} | "
            f"{c['explained_by_injected_defects']} | {c['unexplained']} |"
        )
    lines += [
        "",
        f"**Robustness:** the same year for {len(sweep) - 1} defect seeds, plus the published "
        f"seed run as weekly incremental batches (the tables above are seed "
        f"{results['defect_seed']}, one batch):",
        "",
        "| Seed | Batches | Late files in a later batch | Alarms raised then cleared "
        "| Slowest business error (days) | Defects handled | Quarantine P / R "
        "| Business errors caught (+ open) | Lost-record rows flagged with evidence "
        "| Unexpected exceptions | Unexplained cells |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]

    def dash(v):
        return "–" if v is None else v

    for x in sweep:
        lines.append(
            f"| {x['defect_seed']} | {x['batches']} | {x['late_files_in_later_batch']} | "
            f"{dash(x['transient_exceptions'])} | {dash(x['max_days_to_raise'])} | "
            f"{x['defects_handled']:,} / {x['defects_injected']:,} | "
            f"{x['quarantine_precision']:.0%} / {x['quarantine_recall']:.0%} | "
            f"{x['business_errors_caught']} (+{x['business_errors_open']}) / "
            f"{x['business_errors']} | "
            f"{x['data_loss_rows_flagged_with_evidence']} / {x['data_loss_rows']} | "
            f"{x['unexpected_exceptions']} | {x['unexplained_cells']} |"
        )
    lines += [
        "",
        "Alarms raised then cleared are exceptions that a later batch closes: for example a "
        "duplicate invoice whose reversing credit memo arrives more than 7 days later (the "
        "exporter delays credit memos by up to 10 days). Until it arrives, the duplicate is a "
        "real over-billing, so the alarm is correct; how many occur depends on the seed.",
        "",
        ETL_END,
    ]
    return "\n".join(lines)


def write_etl_report(root: Path) -> dict:
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        build = Path(tmp)
        results = build_etl_results(build)
        write_samples(build, root / "docs" / "samples")
    sweep = []
    for seed in SWEEP_DEFECT_SEEDS:
        with tempfile.TemporaryDirectory() as tmp:
            sweep.append(sweep_summary(build_etl_results(Path(tmp), seed)))
    with tempfile.TemporaryDirectory() as tmp:
        sweep.append(sweep_summary(build_etl_results(Path(tmp), 7, batch_days=WEEKLY)))
    (root / "docs" / "etl_results.json").write_text(
        json.dumps(results, indent=2) + "\n", encoding="utf-8"
    )
    (root / "docs" / "etl_seed_sweep.json").write_text(
        json.dumps(sweep, indent=2) + "\n", encoding="utf-8"
    )
    update_block(root / "README.md", ETL_BEGIN, ETL_END, render_etl_block(results, sweep))
    return results
