"""Regenerate docs/results.json, the charts, and the generated block of README.md."""

from __future__ import annotations

import json
from dataclasses import asdict, replace
from pathlib import Path

from .analysis import CostModel, IntervalResult, compare_intervals, reference_model
from .config import SimConfig
from .db import create_database
from .simulation import run_simulation

README_BEGIN = "<!-- results:begin (generated by `factorysim report`; do not edit) -->"
README_END = "<!-- results:end -->"
ORIGINAL_CLAIMED_INTERVAL = 17
SENSITIVITY_FEES = [5_000, 25_000, 50_000, 100_000, 250_000, 500_000, 1_000_000]
TABLE_INTERVALS = [15, 16, 17, 20, 25, 30]


def build_results(
    base: SimConfig, table_seeds: list[int], sweep_seeds: list[int], sweep: range
) -> dict:
    model = reference_model(base)
    optimum = model.optimal_interval()
    baseline = base.maintenance_interval_days or 30
    table = compare_intervals(base, TABLE_INTERVALS, table_seeds)
    swept = compare_intervals(base, list(sweep), sweep_seeds)

    def expected(interval: int) -> dict:
        loss, spend, events = model.horizon_cost(interval, base.days)
        return {
            "interval": interval,
            "events": events,
            "decay_loss": loss,
            "maintenance_spend": spend,
            "total_cost": loss + spend,
        }

    conn = create_database()
    try:
        baseline_run = run_simulation(conn, base)
    finally:
        conn.close()

    return {
        "config": asdict(base),
        "table_seeds": len(table_seeds),
        "sweep_seeds": len(sweep_seeds),
        "model": {
            "revenue_per_day_no_decay": model.revenue_per_day_no_decay,
            "grade_a_units_per_day": model.decaying_units_per_day * model.base_grade_a_yield,
            "loss_per_pp_day": model.loss_per_pp_day,
            "optimal_interval": optimum,
            "cost_per_day": {str(t): model.cost_per_day(t) for t in range(1, 61)},
        },
        "baseline": expected(baseline),
        "optimal": expected(optimum),
        "original_claim": expected(ORIGINAL_CLAIMED_INTERVAL),
        "fee_thresholds": {
            str(t): model.min_fee_for_interval(t)
            for t in (optimum + 1, ORIGINAL_CLAIMED_INTERVAL, baseline)
        },
        "fee_sensitivity": [
            {"fee": fee, "optimal_interval": model.with_fee(fee).optimal_interval()}
            for fee in SENSITIVITY_FEES
        ],
        "interval_comparison": [asdict(r) for r in table],
        "interval_sweep": [asdict(r) for r in swept],
        "baseline_run": asdict(baseline_run),
    }


def _money(x: float) -> str:
    return f"-${-x:,.0f}" if x < 0 else f"${x:,.0f}"


def render_readme_block(results: dict) -> str:
    cfg, m = results["config"], results["model"]
    base, opt, claim = results["baseline"], results["optimal"], results["original_claim"]
    thresholds = results["fee_thresholds"]
    run = results["baseline_run"]
    rows = {r["interval"]: r for r in results["interval_comparison"]}
    n_seeds = results["table_seeds"]

    lines = [
        README_BEGIN,
        "",
        f"Horizon: {cfg['days']} days · service fee {_money(cfg['maintenance_cost'])} · "
        f"decay {cfg['decay_rate_pp']:g} pp/day after day {cfg['decay_onset_days']} · "
        f"{m['grade_a_units_per_day']:.0f} Grade-A dies/day at full yield · "
        f"each point of decay costs {_money(m['loss_per_pp_day'])}/day",
        "",
        "| Schedule | Services | Fees | Expected decay loss | Expected total |",
        "|---|---:|---:|---:|---:|",
    ]
    for label, r in (
        (f"Every {base['interval']} days (original)", base),
        (f"Every {claim['interval']} days (original README's claim)", claim),
        (f"**Every {opt['interval']} days (optimal)**", opt),
    ):
        lines.append(
            f"| {label} | {r['events']} | {_money(r['maintenance_spend'])} | "
            f"{_money(r['decay_loss'])} | {_money(r['total_cost'])} |"
        )
    lines += [
        "",
        f"- Moving from {base['interval']}-day to {opt['interval']}-day service saves "
        f"**{_money(base['total_cost'] - opt['total_cost'])}/year** "
        f"({_money(opt['maintenance_spend'] - base['maintenance_spend'])} more in fees, "
        f"{_money(base['decay_loss'] - opt['decay_loss'])} less lost yield).",
        f"- The {claim['interval']}-day schedule still loses {_money(claim['decay_loss'])}/year "
        f"to decay, so it leaves {_money(claim['total_cost'] - opt['total_cost'])}/year "
        "on the table versus the optimum.",
        "- The optimum only moves when servicing gets expensive: "
        + ", ".join(
            f"{t}-day service becomes optimal above {_money(fee)} per visit"
            for t, fee in thresholds.items()
        )
        + ".",
        "",
        f"**Simulation cross-check** ({n_seeds} seeds per schedule; cost = fees + revenue "
        "shortfall versus a plant with no decay):",
        "",
        "| Interval | Expected total | Simulated mean | Std. error | Difference |",
        "|---:|---:|---:|---:|---:|",
    ]
    z_scores = []
    for t in TABLE_INTERVALS:
        r = rows[t]
        se = r["simulated_total_cost_std"] / n_seeds**0.5
        z = round((r["simulated_total_cost_mean"] - r["expected_total_cost"]) / se, 1) or 0.0
        z_scores.append(abs(z))
        lines.append(
            f"| {t} days | {_money(r['expected_total_cost'])} | "
            f"{_money(r['simulated_total_cost_mean'])} | {_money(se)} | {z:+.1f} SE |"
        )
    lines += [
        "",
        f"The largest gap is {max(z_scores):.1f} standard errors. Across {len(z_scores)} "
        "independent rows, gaps of about 2 standard errors are normal sampling noise; a modelling "
        "error would show as gaps that grow with the amount of decay.",
    ]
    lines += [
        "",
        f"**Baseline run** (seed {cfg['seed']}, {base['interval']}-day service): "
        f"revenue {_money(run['revenue'])}, material purchases {_money(run['material_spend'])}, "
        f"maintenance {_money(run['maintenance_spend'])}, closing cash "
        f"{_money(run['closing_cash'])}, {run['station_stoppages']} station stoppages.",
        "",
        README_END,
    ]
    return "\n".join(lines)


def update_readme(readme: Path, block: str) -> None:
    text = readme.read_text(encoding="utf-8")
    start, end = text.find(README_BEGIN), text.find(README_END)
    if start < 0 or end < start:
        raise ValueError(f"{readme} has no generated results block")
    readme.write_text(text[:start] + block + text[end + len(README_END) :], encoding="utf-8")


def plot_charts(results: dict, base: SimConfig, out_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir.mkdir(parents=True, exist_ok=True)
    opt = results["model"]["optimal_interval"]
    paths = []

    fig, ax = plt.subplots(figsize=(11, 4))
    for interval, colour in ((base.maintenance_interval_days, "#c0392b"), (opt, "#2471a3")):
        conn = create_database()
        try:
            run_simulation(conn, replace(base, maintenance_interval_days=interval))
            daily = conn.execute(
                "SELECT sim_day, SUM(revenue) FROM sales_ledger GROUP BY sim_day ORDER BY sim_day"
            ).fetchall()
        finally:
            conn.close()
        ax.plot(
            [d for d, _ in daily],
            [r / 1000 for _, r in daily],
            lw=1,
            color=colour,
            label=f"Service every {interval} days",
        )
    ax.set(
        xlabel="Simulation day",
        ylabel="Daily revenue ($k)",
        title="Daily revenue: original vs optimal service interval",
    )
    ax.legend(loc="lower left")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    paths.append(out_dir / "daily_revenue.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)

    model: CostModel = reference_model(base)
    rows = [IntervalResult(**r) for r in results["interval_sweep"]]
    n_seeds = results["sweep_seeds"]
    fig, ax = plt.subplots(figsize=(8, 4.5))
    xs = list(range(5, 41))
    ax.plot(
        xs,
        [sum(model.horizon_cost(t, base.days)[:2]) / 1000 for t in xs],
        color="#555",
        label="Expected",
    )
    ax.errorbar(
        [r.interval for r in rows],
        [r.simulated_total_cost_mean / 1000 for r in rows],
        yerr=[1.96 * r.simulated_total_cost_std / n_seeds**0.5 / 1000 for r in rows],
        fmt="o",
        ms=3,
        color="#2471a3",
        label=f"Simulated mean, 95% CI ({n_seeds} seeds)",
    )
    ax.axvline(opt, color="#27ae60", ls="--", lw=1, label=f"Optimum ({opt} days)")
    ax.set(
        xlabel="Service interval (days)",
        ylabel="Annual fees + lost yield ($k)",
        title="Annual cost of the maintenance policy",
        yscale="log",
    )
    ax.legend()
    ax.grid(alpha=0.3, which="both")
    fig.tight_layout()
    paths.append(out_dir / "interval_cost.png")
    fig.savefig(paths[-1], dpi=120)
    plt.close(fig)
    return paths


def write_report(
    root: Path, base: SimConfig, table_seeds: list[int], sweep_seeds: list[int], sweep: range
) -> dict:
    results = build_results(base, table_seeds, sweep_seeds, sweep)
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "results.json").write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    plot_charts(results, base, docs / "img")
    update_readme(root / "README.md", render_readme_block(results))
    return results
